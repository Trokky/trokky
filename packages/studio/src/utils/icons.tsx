// Convert legacy FaXxx format to fa-xxx format
function normalizeFaIconName(name: string): string {
  if (name.startsWith('Fa') && !name.startsWith('fa-')) {
    // Convert FaFileAlt to fa-file-alt
    return 'fa-' + name.slice(2).replace(/([A-Z])/g, '-$1').toLowerCase().replace(/^-/, '');
  }
  return name;
}

// Parse icon string and return library and name
interface ParsedIcon {
  library: 'heroicons' | 'fontawesome' | 'custom-svg';
  name: string;
  style?: 'stroke' | 'fill';
  viewBox?: string;
}

function parseIconString(iconString: string): ParsedIcon {
  if (!iconString) {
    return { library: 'heroicons', name: 'document' };
  }

  // Format: "svg-fill[viewBox]:path" - Custom SVG with fill style and optional viewBox
  // Format: "svg-fill:path" - Custom SVG with fill style
  if (iconString.startsWith('svg-fill')) {
    const viewBoxMatch = iconString.match(/^svg-fill\[([^\]]+)\]:(.+)$/);
    if (viewBoxMatch) {
      return { library: 'custom-svg', name: viewBoxMatch[2], style: 'fill', viewBox: viewBoxMatch[1] };
    }
    const pathData = iconString.slice(9); // "svg-fill:".length = 9
    return { library: 'custom-svg', name: pathData, style: 'fill' };
  }

  // Format: "svg[viewBox]:path" - Custom SVG with custom viewBox
  // Format: "svg:path" - Custom SVG path (stroke style, default viewBox)
  if (iconString.startsWith('svg')) {
    const viewBoxMatch = iconString.match(/^svg\[([^\]]+)\]:(.+)$/);
    if (viewBoxMatch) {
      return { library: 'custom-svg', name: viewBoxMatch[2], style: 'stroke', viewBox: viewBoxMatch[1] };
    }
    if (iconString.startsWith('svg:')) {
      const pathData = iconString.slice(4); // "svg:".length = 4
      return { library: 'custom-svg', name: pathData, style: 'stroke' };
    }
  }

  // Format: "hi:icon-name" - Heroicons
  if (iconString.startsWith('hi:')) {
    return { library: 'heroicons', name: iconString.slice(3) };
  }

  // Format: "fa:icon-name" - FontAwesome
  if (iconString.startsWith('fa:')) {
    const faName = iconString.slice(3);
    // Convert to heroicon if mapping exists
    const heroName = faToHeroiconMap[`fa-${faName}`] || faToHeroiconMap[faName];
    if (heroName) {
      return { library: 'heroicons', name: heroName };
    }
    return { library: 'fontawesome', name: faName };
  }

  // Format: "FaIconName" - Legacy FontAwesome
  if (iconString.startsWith('Fa')) {
    const normalized = normalizeFaIconName(iconString);
    const heroName = faToHeroiconMap[normalized];
    if (heroName) {
      return { library: 'heroicons', name: heroName };
    }
    return { library: 'fontawesome', name: normalized.replace('fa-', '') };
  }

  // Plain name - assume Heroicons
  return { library: 'heroicons', name: iconString };
}

// Render a heroicon by name
function renderHeroicon(name: string, size: number = 16, className?: string): React.ReactNode {
  const path = heroiconPaths[name];

  if (!path) {
    // Fallback to document icon
    return renderHeroicon('document', size, className);
  }

  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      fill="none"
      viewBox="0 0 24 24"
      strokeWidth={1.5}
      stroke="currentColor"
      width={size}
      height={size}
      className={className}
    >
      <path strokeLinecap="round" strokeLinejoin="round" d={path} />
    </svg>
  );
}

// Render a FontAwesome icon by name (CSS class based)
function renderFontAwesomeIcon(name: string, size: number = 16, className?: string): React.ReactNode {
  const faClass = name.startsWith('fa-') ? `fas ${name}` : `fas fa-${name}`;
  return (
    <i
      className={`${faClass} ${className || ''}`}
      style={{ fontSize: size, width: size, height: size, display: 'inline-flex', alignItems: 'center', justifyContent: 'center' }}
    />
  );
}

// Render a custom SVG icon from path data
function renderCustomSvg(
  pathData: string,
  size: number = 16,
  className?: string,
  style: 'stroke' | 'fill' = 'stroke',
  viewBox: string = '0 0 24 24'
): React.ReactNode {
  if (style === 'fill') {
    return (
      <svg
        xmlns="http://www.w3.org/2000/svg"
        viewBox={viewBox}
        fill="currentColor"
        width={size}
        height={size}
        className={className}
      >
        <path d={pathData} />
      </svg>
    );
  }

  // Default: stroke style (like Heroicons outline)
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      fill="none"
      viewBox={viewBox}
      strokeWidth={1.5}
      stroke="currentColor"
      width={size}
      height={size}
      className={className}
    >
      <path strokeLinecap="round" strokeLinejoin="round" d={pathData} />
    </svg>
  );
}

/**
 * Render an icon by name
 * Supports formats: "hi:name", "fa:name", "FaName", "name", "svg:path", "svg-fill:path"
 */
export function renderIcon(iconString: string, size: number = 16, className?: string): React.ReactNode {
  const parsed = parseIconString(iconString);

  if (parsed.library === 'custom-svg') {
    return renderCustomSvg(parsed.name, size, className, parsed.style, parsed.viewBox);
  }

  if (parsed.library === 'heroicons') {
    return renderHeroicon(parsed.name, size, className);
  }

  return renderFontAwesomeIcon(parsed.name, size, className);
}

/**
 * Icon component for use in JSX
 */
interface IconProps {
  name: string;
  size?: number;
  className?: string;
}

export function Icon({ name, size = 16, className }: IconProps): React.ReactElement {
  return <>{renderIcon(name, size, className)}</>;
}

